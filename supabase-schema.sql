-- 1. Create CUSTOMER DISPATCHES CRM Table
CREATE TABLE IF NOT EXISTS public.dispatches (
    id TEXT PRIMARY KEY,
    type TEXT NOT NULL DEFAULT 'Contact Inquiry',
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    budget TEXT,
    message TEXT,
    status TEXT NOT NULL DEFAULT 'Unread',
    timestamp TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);

-- Index for fast lookup in admin CRM
CREATE INDEX IF NOT EXISTS idx_dispatches_timestamp ON public.dispatches (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_dispatches_status ON public.dispatches (status);

-- 2. Create COURSES LMS Table
CREATE TABLE IF NOT EXISTS public.courses (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    lessons JSONB NOT NULL DEFAULT '[]'::jsonb,
    status TEXT NOT NULL DEFAULT 'Published',
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);

-- 3. Create Demo TODOS Table (from initial Supabase template)
CREATE TABLE IF NOT EXISTS public.todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

-- Enable RLS on all tables
ALTER TABLE public.dispatches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.todos ENABLE ROW LEVEL SECURITY;

-- Dispatches Policies: Allow public creation from web forms + read/manage from Admin
DROP POLICY IF EXISTS "Public insert dispatches" ON public.dispatches;
CREATE POLICY "Public insert dispatches" ON public.dispatches
    FOR INSERT TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow select dispatches" ON public.dispatches;
CREATE POLICY "Allow select dispatches" ON public.dispatches
    FOR SELECT TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "Allow update dispatches" ON public.dispatches;
CREATE POLICY "Allow update dispatches" ON public.dispatches
    FOR UPDATE TO anon, authenticated
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow delete dispatches" ON public.dispatches;
CREATE POLICY "Allow delete dispatches" ON public.dispatches
    FOR DELETE TO anon, authenticated
    USING (true);

-- Courses Policies: Allow public read + admin authoring
DROP POLICY IF EXISTS "Public select courses" ON public.courses;
CREATE POLICY "Public select courses" ON public.courses
    FOR SELECT TO anon, authenticated
    USING (true);

DROP POLICY IF EXISTS "Public manage courses" ON public.courses;
CREATE POLICY "Public manage courses" ON public.courses
    FOR ALL TO anon, authenticated
    USING (true)
    WITH CHECK (true);

-- Todos Policies: Read & Write
DROP POLICY IF EXISTS "Public all todos" ON public.todos;
CREATE POLICY "Public all todos" ON public.todos
    FOR ALL TO anon, authenticated
    USING (true)
    WITH CHECK (true);

